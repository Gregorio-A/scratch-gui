const normalizeLocale = locale => /^pt(?:-|$)/i.test(String(locale || '')) ? 'pt' : 'en';

const format = (message, values) => String(message).replace(/\{([^}]+)\}/g, (match, key) => (
    values && Object.prototype.hasOwnProperty.call(values, key) ? values[key] : match
));

const translate = (locale, key, values) => {
    const messages = normalizeLocale(locale) === 'pt' ? PORTUGUESE : ENGLISH;
    return format(messages[key] || ENGLISH[key] || key, values);
};

const createTranslator = locale => (key, values) => translate(locale, key, values);

module.exports = {
    createTranslator,
    normalizeLocale,
    translate
};
